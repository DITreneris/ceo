/**
 * Generate robots.txt, sitemap.xml, llms.txt, and llms-full.txt from config/sot.json → geo.
 * Usage: node scripts/build-geo-assets.js
 */
/* eslint-env node */
/* eslint-disable no-console */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SOT_PATH = path.join(ROOT, 'config', 'sot.json');

function loadSot() {
  return JSON.parse(fs.readFileSync(SOT_PATH, 'utf8'));
}

function absUrl(siteUrl, url) {
  if (!url) return siteUrl + '/';
  if (/^https?:\/\//i.test(url)) return url;
  return siteUrl + (url.startsWith('/') ? url : '/' + url);
}

function mdLink(siteUrl, item) {
  var href = absUrl(siteUrl, item.url);
  var label = item.label || href;
  var desc = item.description || '';
  if (desc) {
    return '- [' + label + '](' + href + '): ' + desc;
  }
  return '- [' + label + '](' + href + ')';
}

function buildRobotsTxt(geo) {
  const siteUrl = geo.siteUrl.replace(/\/$/, '');
  const lines = [
    '# Generated by scripts/build-geo-assets.js — edit config/sot.json → geo',
    '# LLMs: /llms.txt · /llms-full.txt',
    '',
    'User-agent: *',
    'Allow: /'
  ];
  (geo.crawlers.disallowPaths || []).forEach(function (p) {
    lines.push('Disallow: ' + p);
  });
  lines.push('');
  (geo.crawlers.explicitBots || []).forEach(function (bot) {
    lines.push('User-agent: ' + bot);
    lines.push('Allow: /');
    (geo.crawlers.disallowPaths || []).forEach(function (p) {
      lines.push('Disallow: ' + p);
    });
    lines.push('');
  });
  lines.push('Sitemap: ' + siteUrl + '/sitemap.xml');
  lines.push('');
  return lines.join('\n');
}

function buildSitemapXml(geo) {
  const siteUrl = geo.siteUrl.replace(/\/$/, '');
  const lastmod = new Date().toISOString().slice(0, 10);
  const urls = (geo.sitemap.include || []).map(function (p) {
    const loc = siteUrl + (p.startsWith('/') ? p : '/' + p);
    const priority = p === '/en/' || p === '/en' ? '1.0' : '0.4';
    const changefreq = priority === '1.0' ? 'weekly' : 'monthly';
    return (
      '  <url>\n' +
      '    <loc>' +
      loc +
      '</loc>\n' +
      '    <lastmod>' +
      lastmod +
      '</lastmod>\n' +
      '    <changefreq>' +
      changefreq +
      '</changefreq>\n' +
      '    <priority>' +
      priority +
      '</priority>\n' +
      '  </url>'
    );
  });
  return (
    '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
    urls.join('\n') +
    '\n</urlset>\n'
  );
}

function buildLlmsTxt(geo) {
  const siteUrl = geo.siteUrl.replace(/\/$/, '');
  const llms = geo.llms || {};
  const lines = ['# ' + llms.title, '', '> ' + llms.summary, ''];

  lines.push('## Ecosystem');
  (llms.ecosystem || []).forEach(function (item) {
    lines.push(mdLink(siteUrl, item));
  });
  lines.push('');

  if (geo.entity && geo.entity.founder) {
    var founder = geo.entity.founder;
    lines.push('## Creator');
    lines.push(
      '- [' +
        founder.name +
        '](' +
        absUrl(siteUrl, geo.canonicalPath || '/en/') +
        '): Founder of Prompt Anatomy'
    );
    (founder.sameAs || []).forEach(function (url) {
      var label = url.indexOf('linkedin') !== -1 ? 'LinkedIn' : url.indexOf('x.com') !== -1 || url.indexOf('twitter') !== -1 ? 'X' : url;
      lines.push('- [' + label + '](' + url + '): ' + founder.name + ' profile');
    });
    lines.push('');
  }

  lines.push('## Key pages');
  (llms.keyPages || []).forEach(function (page) {
    lines.push(mdLink(siteUrl, page));
  });
  lines.push('');

  if ((llms.related || []).length) {
    lines.push('## Related');
    llms.related.forEach(function (item) {
      if (typeof item === 'string') {
        lines.push(mdLink(siteUrl, { url: item, label: item }));
      } else {
        lines.push(mdLink(siteUrl, item));
      }
    });
    lines.push('');
  }

  lines.push('## Optional');
  (llms.optionalPages || []).forEach(function (page) {
    lines.push(mdLink(siteUrl, page));
  });
  lines.push('');

  return lines.join('\n');
}

function buildLlmsFullTxt(sot) {
  const geo = sot.geo;
  const siteUrl = geo.siteUrl.replace(/\/$/, '');
  const enUrl = siteUrl + (geo.canonicalPath || '/en/');
  const pricing = (sot.commerce && sot.commerce.pricing) || {};
  const op = sot.pdfGuides && sot.pdfGuides.operating;
  const st = sot.pdfGuides && sot.pdfGuides.strategic;
  const opPrice = pricing.operating || {};
  const stPrice = pricing.strategic || {};
  const founder = geo.entity && geo.entity.founder;
  const disclaimer =
    (sot.legal && sot.legal.responsibleAiDisclaimer) ||
    'This tool generates prompts and training material. Review AI outputs before using them for executive decisions.';

  const lines = [
    '# ' + (geo.llms.title || 'AI Operations Center') + ' — full brief',
    '',
    '> ' + (geo.llms.summary || ''),
    '',
    '## Product',
    '',
    'AI Operations Center is a free CEO/COO weekly operating brief builder at ' +
      enUrl +
      '. Paste KPIs, runway, and context; copy a structured prompt into ChatGPT, Claude, or Gemini. No account required.',
    '',
    '## How the free tool works',
    '',
    '- Modes: Strategic, Daily, Weekly.',
    '- Depths: Fast (short prioritized answer), Deep (analysis and rationale), Board (executive summary with risks and actions).',
    '- Output is a copy-ready operating brief prompt for the executive to review before acting.',
    '',
    '## Paid PDF playbooks',
    ''
  ];

  if (op) {
    lines.push(
      '- ' +
        op.label +
        ': ' +
        (opPrice.pages || op.pages) +
        ' pages, ' +
        (opPrice.now || '') +
        '. ' +
        (op.buyerPromise || '')
    );
  }
  if (st) {
    lines.push(
      '- ' +
        st.label +
        ': ' +
        (stPrice.pages || st.pages) +
        ' pages, ' +
        (stPrice.now || '') +
        '. ' +
        (st.buyerPromise || '')
    );
  }

  const problems = Array.isArray(sot.buyerProblems) ? sot.buyerProblems : [];
  if (problems.length) {
    lines.push('');
    lines.push('## Problems we solve');
    lines.push('');
    lines.push(
      'Built for US CEOs and COOs who need operating cadence and board-ready decisions—not generic prompt tips:'
    );
    lines.push('');
    for (const problem of problems) {
      if (!problem || !problem.label) continue;
      const detail = problem.description ? ' — ' + problem.description : '';
      lines.push('- ' + problem.label + detail);
    }
  }

  lines.push('');
  lines.push('## Privacy model');
  lines.push('');
  lines.push(
    'Saved sessions are stored locally in the browser (localStorage). The page does not upload form inputs to a server for prompt generation.'
  );
  lines.push('');
  lines.push('## Creator and ecosystem');
  lines.push('');
  if (founder) {
    lines.push(
      '- Founder: ' + founder.name + ' (Prompt Anatomy). Profiles: ' + (founder.sameAs || []).join(', ')
    );
  }
  lines.push('- Hub: https://www.promptanatomy.app/');
  lines.push('- Canonical storefront: ' + enUrl);
  lines.push('');
  lines.push('## Responsible use');
  lines.push('');
  lines.push(disclaimer);
  lines.push('');
  lines.push('## See also');
  lines.push('');
  lines.push('- Curated map: ' + siteUrl + '/llms.txt');
  lines.push('- Privacy: ' + siteUrl + '/privacy.html');
  lines.push('- Terms: ' + siteUrl + '/terms.html');
  lines.push('');

  return lines.join('\n');
}

function main() {
  const sot = loadSot();
  if (!sot.geo) {
    console.error('config/sot.json missing geo block');
    process.exit(1);
  }
  const geo = sot.geo;
  fs.writeFileSync(path.join(ROOT, 'robots.txt'), buildRobotsTxt(geo), 'utf8');
  console.log('Wrote robots.txt');
  fs.writeFileSync(path.join(ROOT, 'sitemap.xml'), buildSitemapXml(geo), 'utf8');
  console.log('Wrote sitemap.xml');
  fs.writeFileSync(path.join(ROOT, 'llms.txt'), buildLlmsTxt(geo), 'utf8');
  console.log('Wrote llms.txt');
  fs.writeFileSync(path.join(ROOT, 'llms-full.txt'), buildLlmsFullTxt(sot), 'utf8');
  console.log('Wrote llms-full.txt');
}

main();
